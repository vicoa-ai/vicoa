#!/usr/bin/env node
/**
 * Regenerates `components/files-git-panel/material-file-icons.ts` — the file
 * glyphs shown in the Files tree, tab strip, search palette and the
 * "no preview" card — from the Material Icon Theme (PKief, MIT).
 *
 * The theme ships ~1,000 icons; embedding them all would put ~1.6 MB of SVG in
 * the client bundle, so `ICONS` below is the curated subset. The extension →
 * icon table is *not* curated: it is the theme's own `fileExtensions` map,
 * filtered to the icons we ship, so every extension the theme knows for those
 * icons comes along (e.g. `xlsx`, `xls`, `csv`, `tsv` all resolve to `table`).
 * Adding a file type is therefore one entry in `ICONS`, then a re-run.
 *
 * Fetches from unpkg at the pinned version — nothing is installed, and the
 * output is byte-for-byte reproducible. The theme's SVGs are embedded verbatim.
 *
 * Run: `node scripts/gen-file-icons.mjs`
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VERSION = '5.38.1';
const BASE = `https://unpkg.com/material-icon-theme@${VERSION}`;

/** Icon names as in the theme's `icons/` directory. Order is cosmetic. */
const ICONS = [
  // ── Code ──────────────────────────────────────────────────────────────────
  'astro', 'c', 'clojure', 'cpp', 'csharp', 'css', 'dart', 'elixir', 'erlang',
  'go', 'graphql', 'groovy', 'h', 'haskell', 'hcl', 'hpp', 'html', 'java',
  'javascript', 'kotlin', 'less', 'lua', 'nix', 'ocaml', 'php', 'python', 'r',
  'react', 'react_ts', 'ruby', 'rust', 'sass', 'scala', 'svelte', 'swift',
  'terraform', 'typescript', 'vue', 'webassembly', 'zig',
  // ── Config / data ─────────────────────────────────────────────────────────
  'console', 'database', 'gradle', 'json', 'lock', 'settings', 'toml', 'xml',
  'yaml', 'jupyter', 'log',
  // ── Documents — what an agent hands back that Vicoa can't preview ─────────
  'document', 'markdown', 'pdf', 'table', 'word', 'powerpoint',
  // ── Media / binaries ──────────────────────────────────────────────────────
  'image', 'svg', 'audio', 'video', 'font', 'zip', 'exe', 'dll',
];

/** The fallback for anything unmapped: the theme's plain `file` glyph. */
const DEFAULT_ICON = 'file';

async function fetchText(path) {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${path}`);
  return res.text();
}

const manifest = JSON.parse(await fetchText('dist/material-icons.json'));
const wanted = new Set(ICONS);

// Single-segment, lower-case extensions only: `getExtension()` at runtime
// lower-cases the text after the last dot, so the theme's compound keys
// (`test.ts`, `d.ts`) and mixed-case ones (`YAML-tmLanguage`) could never
// match and would only mislead a reader. Dot-files come through as their
// bare name (`.zshrc` → `zshrc`), which is exactly what the theme keys on.
const extensionToIcon = [
  ...new Map(
    Object.entries(manifest.fileExtensions)
      .filter(([ext, icon]) => wanted.has(icon) && !ext.includes('.'))
      .map(([ext, icon]) => [ext.toLowerCase(), icon]),
  ),
].sort(([a], [b]) => a.localeCompare(b));

const svgs = new Map();
for (const name of [DEFAULT_ICON, ...ICONS].sort()) {
  const svg = (await fetchText(`icons/${name}.svg`)).trim();
  if (svg.includes('`') || svg.includes('${')) {
    throw new Error(`${name}.svg contains template-literal syntax; escape it`);
  }
  svgs.set(name, svg);
}

const lines = [
  `// Auto-generated by scripts/gen-file-icons.mjs from material-icon-theme@${VERSION}`,
  '// (MIT, https://github.com/material-extensions/vscode-material-icon-theme).',
  '// Do not edit manually — add an icon name to the script and re-run it.',
  '',
  'const SVG_ICONS: Record<string, string> = {',
  `  _default: \`${svgs.get(DEFAULT_ICON)}\`,`,
  ...ICONS.slice().sort().map((name) => `  ${name}: \`${svgs.get(name)}\`,`),
  '};',
  '',
  'const EXTENSION_TO_ICON: Record<string, string> = {',
  ...extensionToIcon.map(([ext, icon]) => `  ${JSON.stringify(ext)}: ${JSON.stringify(icon)},`),
  '};',
  '',
  'export function getFileIconSvg(fileName: string): string {',
  '  const ext = getExtension(fileName);',
  '  if (ext) {',
  '    const iconName = EXTENSION_TO_ICON[ext];',
  '    if (iconName && SVG_ICONS[iconName]) return SVG_ICONS[iconName];',
  '  }',
  '  return SVG_ICONS["_default"];',
  '}',
  '',
  'function getExtension(name: string): string | null {',
  '  const idx = name.lastIndexOf(".");',
  '  if (idx === -1 || idx === name.length - 1) return null;',
  '  return name.slice(idx + 1).toLowerCase();',
  '}',
  '',
];

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'components', 'files-git-panel', 'material-file-icons.ts');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${ICONS.length} icons, ${extensionToIcon.length} extensions`);
